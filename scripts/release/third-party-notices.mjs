#!/usr/bin/env node
// THIRD-PARTY-NOTICES.md (20 §2.4 "Third-party notices"; 20 §8 R-06; NFR-COMP-07; ISSUE-272).
//
//   node scripts/release/third-party-notices.mjs [--root <dir>] [--out <dir>]
//
// Generated from the same data as the licence report: every production dependency with its SPDX licence and its
// licence text, Electron's own licence and Chromium's licence file that Electron ships beside the executable, each
// bundled provider adapter or library with its NOTICE text (S-008-1), and the font, audio and artwork credits. Writes
// <out>/THIRD-PARTY-NOTICES.md (default release/licenses/). Reads the lockfile and installed files only.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildLicenceReport, DEFAULT_OUT, DENIED_FILE, parseArgs, readDenied } from './licenses.mjs'
import { inS008Scope, readS008Rows, S008_RECORD } from './s008-records.mjs'

export const NOTICES_FILE = 'THIRD-PARTY-NOTICES.md'
export const CREDITS_FILES = ['FONT-CREDITS.md', 'AUDIO-CREDITS.md', 'ARTWORK-LICENSE.md']
/** The file Electron ships beside the executable with Chromium's licences (`20` §2.4). */
export const CHROMIUM_LICENCES = 'LICENSES.chromium.html'

const LICENCE_FILE = /^(?:licen[cs]e|copying)(?:[.-].*)?$/i
const NOTICE_FILE = /^notice(?:\..*)?$/i

function filesIn(dir, pattern) {
  if (!dir || !existsSync(dir)) return []
  return readdirSync(dir)
    .filter((name) => pattern.test(name))
    .sort()
    .map((name) => readFileSync(path.join(dir, name), 'utf8').replace(/\r\n/g, '\n').trim())
}

function fenced(text) {
  const fence = '`'.repeat(Math.max(3, ...[...text.matchAll(/`+/g)].map((m) => m[0].length + 1)))
  return `${fence}text\n${text}\n${fence}`
}

function required(rootDir, relative) {
  const file = path.join(rootDir, relative)
  if (!existsSync(file)) throw new Error(`${relative.replaceAll('\\', '/')} is missing`)
  return readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim()
}

/**
 * The licence texts of one package: its own licence files, or, for a platform binary that ships none (an
 * optional `<main>-<platform>` package such as `@napi-rs/keyring-win32-x64-msvc`), its main package's texts under
 * the same licence, which is what the S-008-1 decision records for that binary.
 */
function licenceTexts(pkg, packages) {
  const own = filesIn(pkg.dir, LICENCE_FILE)
  if (own.length > 0) return own
  const main = packages
    .filter((p) => p !== pkg && p.license === pkg.license && pkg.name.startsWith(`${p.name}-`))
    .sort((a, b) => b.name.length - a.name.length)[0]
  return main ? filesIn(main.dir, LICENCE_FILE) : []
}

function packageSection(pkg, packages, { withNotice }) {
  const parts = [`### ${pkg.name} ${pkg.version} (${pkg.license})`]
  if (withNotice) {
    const notices = filesIn(pkg.dir, NOTICE_FILE)
    parts.push(
      notices.length > 0
        ? `NOTICE:\n\n${notices.map(fenced).join('\n\n')}`
        : 'The package ships no NOTICE file (S-008-1).'
    )
  }
  const texts = licenceTexts(pkg, packages)
  parts.push(
    texts.length > 0
      ? texts.map(fenced).join('\n\n')
      : `The package ships no licence file; its package.json declares ${pkg.license}.`
  )
  return parts.join('\n\n')
}

/** The THIRD-PARTY-NOTICES.md text for a licence report. Throws when an input it must carry is missing. */
export function buildNotices({ rootDir, report, rows = [] }) {
  const electronLicence = required(rootDir, path.join('node_modules', 'electron', 'LICENSE'))
  const electron = JSON.parse(
    required(rootDir, path.join('node_modules', 'electron', 'package.json'))
  )
  const credits = CREDITS_FILES.map((file) => [file, required(rootDir, file)])
  const bundled = report.packages.filter((p) => inS008Scope(p.name, rows))
  const others = report.packages.filter((p) => !bundled.includes(p))
  const { name, version, license } = report.product

  return `${[
    '# Third-party notices',
    `${name} ${version} is licensed under ${license}; the licence text is the \`LICENSE\` file shipped beside this one. ` +
      'It includes the third-party software and assets listed below, each under its own licence. ' +
      'This file is generated by `scripts/release/third-party-notices.mjs` from the lockfile and the installed packages.',
    '## Electron and Chromium',
    `### Electron ${electron.version} (${electron.license})`,
    fenced(electronLicence),
    `Chromium and the other components Electron embeds are licensed as listed in \`${CHROMIUM_LICENCES}\`, ` +
      'which Electron ships beside the application executable.',
    '## Bundled provider adapters and libraries',
    bundled.length > 0
      ? `Each is bundled under its S-008-1 record (\`${S008_RECORD.replaceAll('\\', '/')}\`).`
      : 'None is bundled in this build.',
    ...bundled.map((p) => packageSection(p, report.packages, { withNotice: true })),
    '## Production dependencies',
    ...others.map((p) => packageSection(p, report.packages, { withNotice: false })),
    '## Fonts, audio and artwork',
    // Each credits file keeps its own text; its headings move two levels down, under this section.
    ...credits.map(([, text]) => text.replace(/^(#+) /gm, '##$1 '))
  ].join('\n\n')}\n`
}

function main() {
  const args = parseArgs(process.argv.slice(2))
  const rootDir = path.resolve(args.root ?? '.')
  const out = path.resolve(rootDir, args.out ?? DEFAULT_OUT)
  const report = buildLicenceReport({
    rootDir,
    denied: readDenied(path.join(rootDir, DENIED_FILE))
  })
  const notices = buildNotices({ rootDir, report, rows: readS008Rows(rootDir) })
  mkdirSync(out, { recursive: true })
  writeFileSync(path.join(out, NOTICES_FILE), notices)
  console.log(
    `wrote ${path.join(out, NOTICES_FILE)}: ${report.packages.length} packages, ${notices.length} characters`
  )
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
