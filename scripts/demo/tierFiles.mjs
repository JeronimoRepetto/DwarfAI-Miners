import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

/**
 * The fictional source files that give a demo mine its tier (docs/demo.md "How the mines get their tiers").
 *
 * A mine's tier is the Host's own measurement of its folder (`mines/domain/tier.ts`, INV-05: never from ore): the
 * bytes of its source-ish files, each under the bundle ceiling, byte-identical copies counted once
 * (`mines/adapters/sourceWeight/sourceWalk.ts`). The demo never changes that rule nor the database: it writes a folder
 * the walk weighs into the wanted band, so the tier shown is the one a person's project of that size gets. The plan is
 * kept in step with both rules by `tierFiles.test.mjs`, which runs the Host's walk and tier rule over it.
 *
 * Default band floors, in KB: Copper 350, Silver 1 500, Gold 12 000, Uranium 100 000. A Uranium demo mine is therefore
 * about 100 MB of generated text in the OS temp folder, removed with the profile.
 */

/** The default band floors in KB (`DEFAULT_TIER_THRESHOLDS`); Bronze starts at 0. */
const FLOOR_KB = Object.freeze({
  bronze: 0,
  copper: 350,
  silver: 1_500,
  gold: 12_000,
  uranium: 100_000
})

/** What a Bronze mine weighs: well inside its band, so it still looks like a small project. */
const BRONZE_KB = 120

/** How far above its band's floor a planned mine lands: never on the edge of the band below. */
const MARGIN = 1.04

/** One file's size: under the walk's 300 KB bundle ceiling. */
const FILE_BYTES = 240 * 1024

/** Fictional module folders the files are spread over, so the folder reads like a project. */
const AREAS = Object.freeze([
  'core',
  'tunnels',
  'ledger',
  'lanterns',
  'carts',
  'forge',
  'vault',
  'maps'
])

/** The files of a mine of `tier`: `{ relativePath, bytes, seed }`, posix paths under the mine folder. */
export function tierFilePlan(tier) {
  if (!Object.hasOwn(FLOOR_KB, tier)) throw new Error(`unknown tier ${tier}`)
  const target = tier === 'bronze' ? BRONZE_KB * 1024 : Math.ceil(FLOOR_KB[tier] * 1024 * MARGIN)
  const plan = []
  let left = target
  for (let seed = 0; left > 0; seed++) {
    const bytes = Math.min(FILE_BYTES, left)
    const area = AREAS[seed % AREAS.length]
    plan.push({
      relativePath: `src/${area}/${area}-${String(seed).padStart(4, '0')}.ts`,
      bytes,
      seed
    })
    left -= bytes
  }
  return plan
}

/**
 * The text of one planned file: exactly `bytes` ASCII bytes. Its first line names its seed, so no two files of a plan
 * share their first 4 KB (the walk's duplicate fingerprint); the rest is plain, fictional TypeScript.
 */
export function fileText(seed, bytes) {
  const head = `// Fictional demo source ${seed}: generated by scripts/demo for DwarfAI-Miners' showcase.\n`
  const lines = [head]
  let size = head.length
  for (let line = 0; size < bytes; line++) {
    const text = `export const seam${seed}_${line} = { depth: ${(seed * 31 + line) % 997}, lit: ${line % 2 === 0} }\n`
    lines.push(text)
    size += text.length
  }
  return lines.join('').slice(0, bytes)
}

/** Writes the plan's files under `folder`. */
export function writeTierFiles(folder, plan) {
  for (const file of plan) {
    const target = path.join(folder, ...file.relativePath.split('/'))
    mkdirSync(path.dirname(target), { recursive: true })
    writeFileSync(target, fileText(file.seed, file.bytes))
  }
}
